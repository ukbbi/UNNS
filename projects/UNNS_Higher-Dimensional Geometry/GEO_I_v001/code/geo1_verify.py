def analyse(x0,steps,tail,maxP):
    xs=[Fr(x0)]
    while len(xs)<steps:
        y=Cstep(xs[-1])
        if y is None: return None
        xs.append(Fr(y))
    for P in range(1,maxP+1):
        rr=None; ok=True
        for n in range(len(xs)-tail-P,len(xs)-P):
            q=xs[n+P]/xs[n]
            if rr is None: rr=q
            elif q!=rr: ok=False;break
        if ok and rr.denominator==1 and rr>1 and isqrt(rr.numerator)**2==rr.numerator: return P,isqrt(rr.numerator),xs
    return 'undetected'
def quasi_check(xs,P,p,s,tail):
    """predict R(x_{n+mP}) = sum_{j<=h+ms} c(j) - 1 with c(j)=#{t in box_{!=p}: prod q^t_q p^j = 1 mod b}"""
    fails=0;chk=0;slopes=[]
    for ph in range(len(xs)-tail,len(xs)-tail+P):
        x=xs[ph]; fa=factor(x.numerator); bb=x.denominator
        qs=sorted(q for q,e in fa.items() if e//2 and q!=p); hq=[fa[q]//2 for q in qs]; h0=fa.get(p,0)//2
        res=[prod(pow(q,e,bb) for q,e in zip(qs,k))%bb if bb>1 else 0 for k in itertools.product(*[range(e+1) for e in hq])]
        c=lambda j: sum(1 for r in res if bb==1 or (r*pow(p,j,bb))%bb==1%bb)
        for m in range(4):
            if ph+m*P>=len(xs): break
            chk+=1
            if len(fibre_q(xs[ph+m*P]))!=sum(c(j) for j in range(h0+m*s+1))-1: fails+=1
        # average increment per layer over a full residue period
        if bb>1:
            o=1
            while pow(p,o,bb)!=1: o+=1
            Qp=sum(1 for r in res if any((r*pow(p,j,bb))%bb==1 for j in range(o)))
            slopes.append(Fr(s*Qp,o*P))
        else:
            slopes.append(Fr(s*len(res),P))
    return fails,chk,slopes
