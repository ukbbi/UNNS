"""GIG-INFO v005 -- dead sets and the nerve model of the forbidden complex Y_A (k=6).
Y_A = complex generated by prefix chains of non-admissible histories (v004 forbidden.py).
Dead set: proper nonempty I such that every history through the prefix set I is non-admissible.
Nerve complex N[D]: simplices = subsets T of D for which some proper nonempty z is comparable (under inclusion, equality allowed) with every member of T.
Model (tested, see THEORY): H~_j(Y_A) = H~_j(N[D_A]) for j=0,1 whenever the system is prefix-defined; verified computationally in A20."""
import itertools
import _vpath  # noqa: F401
import forbidden as fb

K = 6
FULL = (1 << K) - 1
SUBS = list(range(1, FULL))                      # 62 proper nonempty subsets
_through = None


def through():
    global _through
    if _through is None:
        t = {I: 0 for I in SUBS}
        for i, c in enumerate(fb.chains(K)):
            for I in c:
                t[I] |= 1 << i
        _through = t
    return _through


def comparable(a, b):
    return (a & b) == a or (a & b) == b


COMP = {z: frozenset(x for x in SUBS if comparable(x, z)) for z in SUBS}


def dead_sets(mask):
    t = through()
    return frozenset(I for I in SUBS if t[I] & mask == 0)


def forbidden_prefix_sets(mask):
    """subsets I appearing as a prefix of some non-admissible history"""
    out = set()
    for i, c in enumerate(fb.chains(K)):
        if not (mask >> i & 1):
            out.update(c)
    return out


def is_prefix_defined(mask):
    """True iff admissibility is determined by prefix sets: a history is admissible iff none of its prefix sets is dead."""
    D = dead_sets(mask)
    for i, c in enumerate(fb.chains(K)):
        adm = bool(mask >> i & 1)
        if adm == any(I in D for I in c):
            return False
    return True


def facets(D):
    """maximal faces D & COMP(z)"""
    fs = {frozenset(D & COMP[z]) for z in SUBS}
    fs.discard(frozenset())
    return fs


def nerve_betti(D, top=1):
    """reduced GF(2) Betti numbers b~_0..b~_top of N[D] (top<=1 uses the 2-skeleton)."""
    D = sorted(D)
    if not D:
        return [0] * (top + 1)  # empty complex: convention; callers handle D empty separately
    F = facets(frozenset(D))
    vid = {v: i for i, v in enumerate(D)}
    edges = set(); tris = set()
    for f in F:
        fl = sorted(f)
        for e in itertools.combinations(fl, 2):
            edges.add(e)
        if top >= 1:
            for t in itertools.combinations(fl, 3):
                tris.add(t)
    edges = sorted(edges); eid = {e: i for i, e in enumerate(edges)}
    r1 = fb.gf2_rank([(1 << vid[a]) ^ (1 << vid[b]) for a, b in edges])
    b0 = len(D) - r1 - 1
    res = [b0]
    if top >= 1:
        r2 = fb.gf2_rank([(1 << eid[(a, b)]) ^ (1 << eid[(a, c)]) ^ (1 << eid[(b, c)]) for a, b, c in tris])
        res.append(len(edges) - r1 - r2)
    return res


def y_betti(mask, top=1):
    return fb.reduced_betti(fb.y_simplices(mask, K), top)


# ---- cycle machinery on N[D] ------------------------------------------------
def nerve_complex(D):
    """edges and triangles of N[D] (as sorted tuples), vertex list."""
    D = sorted(D)
    F = facets(frozenset(D))
    edges, tris = set(), set()
    for f in F:
        fl = sorted(f)
        edges.update(itertools.combinations(fl, 2))
        tris.update(itertools.combinations(fl, 3))
    return D, sorted(edges), sorted(tris)


class Bounder:
    """GF(2) boundary space of the 2-skeleton of N[D]: bounds(cycle) iff the edge-vector lies in span of triangle boundaries."""
    def __init__(self, D):
        self.D, self.edges, self.tris = nerve_complex(D)
        self.eid = {e: i for i, e in enumerate(self.edges)}
        self.piv = {}
        for a, b, c in self.tris:
            self._add((1 << self.eid[(a, b)]) ^ (1 << self.eid[(a, c)]) ^ (1 << self.eid[(b, c)]))
        self.edgeset = set(self.edges)

    def _add(self, r):
        while r:
            h = r.bit_length() - 1
            if h in self.piv:
                r ^= self.piv[h]
            else:
                self.piv[h] = r; return True
        return False

    def reduce(self, r):
        while r:
            h = r.bit_length() - 1
            if h in self.piv:
                r ^= self.piv[h]
            else:
                return r
        return 0

    def vec(self, cyc):
        r = 0
        n = len(cyc)
        for i in range(n):
            a, b = cyc[i], cyc[(i + 1) % n]
            r ^= 1 << self.eid[(min(a, b), max(a, b))]
        return r

    def bounds(self, cyc):
        return self.reduce(self.vec(cyc)) == 0


def live_sets(mask):
    return frozenset(SUBS) - dead_sets(mask)


def mask_of_orderings(orders):
    import history_complex as hc
    idx = {p: i for i, p in enumerate(hc.perms(K))}
    m = 0
    for p in orders:
        m |= 1 << idx[tuple(p)]
    return m


def arithmetic_mask(content, m0):
    """admissible-history mask by direct simulation (definition-level, independent of the frozen engines)."""
    from itertools import permutations
    labs = sorted(content)
    ords = []
    for p in permutations(range(K)):
        m, ok = m0, True
        for r in p:
            n = labs[r]
            if m % n:
                ok = False; break
            m = m // n * (n + 1) ** 2
        if ok:
            ords.append(p)
    return mask_of_orderings(ords)


def label_set(I, content):
    labs = sorted(content)
    return "{" + ",".join(str(labs[i]) for i in range(K) if I >> i & 1) + "}"


def cocycle_certificate(D, cyc):
    """if the edge-cycle cyc does not bound in N[D], return an edge cocycle c (set of edges, c(d triangle)=0 for all triangles) with c(cyc)=1; else None."""
    Dl, edges, tris = nerve_complex(D)
    eid = {e: i for i, e in enumerate(edges)}
    rows = [(1 << eid[(a, b)]) ^ (1 << eid[(a, c)]) ^ (1 << eid[(b, c)]) for a, b, c in tris]
    piv = {}
    for r in rows:                          # echelon on leading bit
        while r:
            h = r.bit_length() - 1
            if h in piv: r ^= piv[h]
            else: piv[h] = r; break
    # full reduction
    keys = sorted(piv)
    for h in keys:
        for h2 in keys:
            if h2 > h and (piv[h2] >> h) & 1:
                piv[h2] ^= piv[h]
    z = 0
    n = len(cyc)
    for i in range(n):
        a, b = cyc[i], cyc[(i + 1) % n]
        z ^= 1 << eid[(min(a, b), max(a, b))]
    free = [j for j in range(len(edges)) if j not in piv]
    for f in free:
        c = 1 << f
        for h, row in piv.items():
            if (row >> f) & 1:
                c |= 1 << h
        if bin(c & z).count("1") % 2:
            return [edges[j] for j in range(len(edges)) if c >> j & 1], edges, tris
    return None


def check_cocycle(c_edges, D, cyc):
    Dl, edges, tris = nerve_complex(D)
    cs = set(c_edges)
    for a, b, c in tris:
        if ((a, b) in cs) ^ ((a, c) in cs) ^ ((b, c) in cs):
            return False
    n = len(cyc); val = 0
    for i in range(n):
        a, b = cyc[i], cyc[(i + 1) % n]
        val ^= int((min(a, b), max(a, b)) in cs)
    return val == 1


# ---- v006: strong-collapse core of N[D] -------------------------------------
def _facet_masks(D):
    Dl = sorted(D); idx = {v: i for i, v in enumerate(Dl)}
    fs = set()
    for z in SUBS:
        m = 0
        for x in COMP[z]:
            if x in idx: m |= 1 << idx[x]
        if m: fs.add(m)
    return Dl, idx, _maximal(fs)


def _maximal(fs):
    fs = sorted(set(fs), key=lambda m: -m.bit_count())
    out = []
    for m in fs:
        if not any(m & o == m for o in out): out.append(m)
    return out


def strong_core(D):
    """repeatedly delete dominated vertices (v dominated by w: every maximal face containing v contains w); homotopy type is preserved.
    returns (list of remaining dead sets, facets as frozensets of dead sets)."""
    Dl, idx, F = _facet_masks(D)
    alive = (1 << len(Dl)) - 1
    changed = True
    while changed:
        changed = False
        for v in range(len(Dl)):
            if not (alive >> v & 1): continue
            inter = alive
            for f in F:
                if f >> v & 1: inter &= f
            inter &= ~(1 << v)
            if inter:                      # some w in all facets containing v (v lies in >=1 facet)
                alive &= ~(1 << v)
                F = _maximal({f & ~(1 << v) for f in F} - {0})
                changed = True
    verts = [Dl[v] for v in range(len(Dl)) if alive >> v & 1]
    return verts, [frozenset(Dl[v] for v in range(len(Dl)) if f >> v & 1) for f in F]


def complex_betti_from_facets(verts, facets, top=1):
    """reduced GF(2) b~_0, b~_1 of the complex generated by facets (2-skeleton)."""
    if not verts: return [0] * (top + 1)
    vid = {v: i for i, v in enumerate(sorted(verts))}
    edges, tris = set(), set()
    for f in facets:
        fl = sorted(f)
        edges.update(itertools.combinations(fl, 2)); tris.update(itertools.combinations(fl, 3))
    edges = sorted(edges); eid = {e: i for i, e in enumerate(edges)}
    r1 = fb.gf2_rank([(1 << vid[a]) ^ (1 << vid[b]) for a, b in edges])
    r2 = fb.gf2_rank([(1 << eid[(a, b)]) ^ (1 << eid[(a, c)]) ^ (1 << eid[(b, c)]) for a, b, c in sorted(tris)])
    return [len(verts) - r1 - 1, len(edges) - r1 - r2]
