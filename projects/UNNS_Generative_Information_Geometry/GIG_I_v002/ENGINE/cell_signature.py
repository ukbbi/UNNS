"""GIG-I v002 -- cell-level information of an arrangement set, and the colour-graph reconstruction (theorem GIG-T13).

reconstruct(): builds the faces of the full subcomplex K_A ONLY from the generator-coloured swap graph (no permutations
are consulted): a face is a connected component of the J-coloured subgraph whose size equals |W_J| (the order of the
parabolic subgroup generated by the colours J).  Boundary = containment of vertex sets.  Independent of history_complex.
"""
import _v1path  # noqa: F401
from math import factorial
import history_complex as hc


def colored_graph(mask, k):
    """(vertex perm indices, coloured edge list [(u,v,colour 1..k-1)]) of the induced swap graph on `mask`."""
    P = hc.perms(k)
    pidx = hc.perm_index(k)
    verts = [i for i in range(len(P)) if mask >> i & 1]
    loc = {v: j for j, v in enumerate(verts)}
    edges = []
    for v in verts:
        p = P[v]
        for j in range(k - 1):
            q = p[:j] + (p[j + 1], p[j]) + p[j + 2:]
            w = pidx[q]
            if w in loc and w > v:
                edges.append((loc[v], loc[w], j + 1))
    return verts, edges


def parabolic_order(J):
    """|W_J| for a set J of generator colours (maximal runs of consecutive colours r give blocks of size r+1)."""
    Js = sorted(J)
    o, run = 1, 0
    for i, j in enumerate(Js):
        if i and j == Js[i - 1] + 1:
            run += 1
        else:
            o *= factorial(run + 1)
            run = 1
    if Js:
        o *= factorial(run + 1)
    return o


def _components(n, edges, J):
    par = list(range(n))

    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]
            x = par[x]
        return x
    for u, v, c in edges:
        if c in J:
            a, b = find(u), find(v)
            if a != b:
                par[a] = b
    comps = {}
    for v in range(n):
        comps.setdefault(find(v), []).append(v)
    return list(comps.values())


def _rank(rows):
    piv, r = {}, 0
    for x in rows:
        while x:
            h = x.bit_length() - 1
            if h in piv:
                x ^= piv[h]
            else:
                piv[h] = x
                r += 1
                break
    return r


def reconstruct(n, edges, k):
    """faces, boundary ranks and GF(2) Betti numbers from the coloured graph (n vertices, coloured edges).
    Returns dict f, ranks (rank d_1..d_{k-1}), betti, faces count."""
    gens = list(range(1, k))
    faces = {}                      # (J tuple, comp id) -> frozenset
    bydim = {d: [] for d in range(k)}
    for bits in range(1 << (k - 1)):
        J = tuple(g for g in gens if bits >> (g - 1) & 1)
        need = parabolic_order(J) if J else 1
        for comp in _components(n, edges, set(J)):
            if len(comp) == need:
                fs = frozenset(comp)
                faces[(J, min(comp))] = fs
                bydim[len(J)].append((J, min(comp)))
    f = tuple(len(bydim[d]) for d in range(k))
    index = {d: {fid: i for i, fid in enumerate(L)} for d, L in bydim.items()}
    ranks = [0] * (k + 1)
    for d in range(1, k):
        # facets of a d-face: faces of dim d-1 with colour set J minus one colour, vertex set contained
        lower = {}
        for fid in bydim[d - 1]:
            lower.setdefault(fid[0], []).append(fid)
        rows = []
        for fid in bydim[d]:
            J, _ = fid
            V = faces[fid]
            row = 0
            for j in J:
                Jp = tuple(x for x in J if x != j)
                for g in lower.get(Jp, ()):
                    if faces[g] <= V:
                        row ^= 1 << index[d - 1][g]
            rows.append(row)
        ranks[d] = _rank(rows)
    betti = tuple(f[d] - ranks[d] - ranks[d + 1] for d in range(k))
    return {"f": f, "ranks": tuple(ranks[1:k]), "betti": betti}


def cell_data(mask, k):
    """cell information of K_A from the coloured graph; includes the Euler-characteristic identity check."""
    verts, edges = colored_graph(mask, k)
    r = reconstruct(len(verts), edges, k)
    chi_f = sum((-1) ** d * c for d, c in enumerate(r["f"]))
    chi_b = sum((-1) ** d * c for d, c in enumerate(r["betti"]))
    r["euler"] = chi_f
    r["euler_ok"] = chi_f == chi_b
    r["N"], r["E"] = len(verts), len(edges)
    return r


def adjacency(mask, k):
    verts, edges = colored_graph(mask, k)
    adj = [[] for _ in verts]
    for u, v, c in edges:
        adj[u].append(v)
        adj[v].append(u)
    for a in adj:
        a.sort()
    return adj


