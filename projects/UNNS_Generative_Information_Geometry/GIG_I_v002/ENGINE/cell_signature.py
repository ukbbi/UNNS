# GIG-T15: for sets with the cube-product property, beta_0 and beta_1 are functions of the UNCOLOURED graph.
# 2-faces of K_A = all 4-cycles of G_A (squares) + all chordless 6-cycles of G_A (braid hexagons).
def _cycles(adj, length):
    """all simple cycles of the given length as tuples of vertices, each once (smallest vertex first, fixed orientation)."""
    n = len(adj)
    S = [set(a) for a in adj]
    out = []

    def rec(path):
        v = path[-1]
        if len(path) == length:
            if path[0] in S[v] and path[1] < path[-1]:
                out.append(tuple(path))
            return
        for u in adj[v]:
            if u > path[0] and u not in path:
                path.append(u)
                rec(path)
                path.pop()
    for s in range(n):
        rec([s])
    return out


def graph_two_cells(adj):
    """(squares, hexagons, petrie) derived from the uncoloured graph alone.
    squares  = all 4-cycles;
    chordless 6-cycles are braid hexagons or Petrie cycles of a commuting cube (E5 classification of P_6); a Petrie
    cycle is recognised graph-theoretically: some vertex outside the cycle is adjacent to >= 2 of its vertices (in a
    realizable set the cube is complete by T11), whereas no vertex is adjacent to two vertices of a braid hexagon face.
    hexagons = chordless 6-cycles without such a vertex."""
    S = [set(a) for a in adj]
    sq = _cycles(adj, 4)
    hx, pet = [], []
    for c in _cycles(adj, 6):
        cs_ = set(c)
        chords = sum(1 for v in c for u in S[v] if u in cs_) // 2 - 6
        if chords:
            continue
        outside = {}
        for v in c:
            for u in S[v]:
                if u not in cs_:
                    outside[u] = outside.get(u, 0) + 1
        (pet if any(x >= 2 for x in outside.values()) else hx).append(c)
    return sq, hx, pet


def graph_only_betti01(adj):
    """(beta_0, beta_1, f_2) from the uncoloured graph under the T15 hypothesis (squares = 4-cycles, hexagons =
    chordless 6-cycles).  Valid for arrangement sets with the commuting-cube product property."""
    n = len(adj)
    eid = {}
    for v in range(n):
        for u in adj[v]:
            if v < u:
                eid[(v, u)] = len(eid)
    E = len(eid)
    par = list(range(n))

    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]
            x = par[x]
        return x
    for (u, v) in eid:
        par[find(u)] = find(v)
    c = len({find(v) for v in range(n)}) if n else 0
    sq, hx, pet = graph_two_cells(adj)
    rows = []
    for cyc in sq + hx + pet:
        r = 0
        for i in range(len(cyc)):
            a, b = cyc[i], cyc[(i + 1) % len(cyc)]
            r ^= 1 << eid[(min(a, b), max(a, b))]
        rows.append(r)
    rk = _rank(rows)
    return c, (E - n + c) - rk, len(sq) + len(hx)  # f_2 counts faces: Petrie cycles are NOT faces (but are boundaries)


def six_cycle_census(adj):
    """counts of the 6-cycles of an uncoloured swap graph by graph-recognisable type, and the number of components that
    contain a braid hexagon face / a non-braid 6-cycle: {'braid':.., 'petrie':.., 'chorded':.., 'comp_braid':.., 'comp_nonbraid':.., 'comp_both':..}"""
    S = [set(a) for a in adj]
    comp = [-1] * len(adj)
    c = 0
    for s in range(len(adj)):
        if comp[s] < 0:
            comp[s] = c
            st = [s]
            while st:
                v = st.pop()
                for u in adj[v]:
                    if comp[u] < 0:
                        comp[u] = c
                        st.append(u)
            c += 1
    br = pe = ch = 0
    cb, cn = set(), set()
    for cyc in _cycles(adj, 6):
        cset = set(cyc)
        chords = sum(1 for v in cyc for u in S[v] if u in cset) // 2 - 6
        if chords:
            ch += 1
            cn.add(comp[cyc[0]])
            continue
        outside = {}
        for v in cyc:
            for u in S[v]:
                if u not in cset:
                    outside[u] = outside.get(u, 0) + 1
        if any(x >= 2 for x in outside.values()):
            pe += 1
            cn.add(comp[cyc[0]])
        else:
            br += 1
            cb.add(comp[cyc[0]])
    return {"braid": br, "petrie": pe, "chorded": ch, "comp_braid": len(cb), "comp_nonbraid": len(cn), "comp_both": len(cb & cn)}


def shortest_unfilled_cycle(adj, maxlen=10):
    """length of the shortest simple cycle of the swap graph that is NOT a GF(2) combination of the 2-faces (squares and
    braid hexagons) -- i.e. a non-bounding cycle; searched exhaustively for even lengths 4..maxlen (graph is bipartite).
    Returns None if there is none up to maxlen."""
    eid = {}
    for v in range(len(adj)):
        for u in adj[v]:
            if v < u:
                eid[(v, u)] = len(eid)

    def vec(cyc):
        r = 0
        for i in range(len(cyc)):
            a, b = cyc[i], cyc[(i + 1) % len(cyc)]
            r ^= 1 << eid[(min(a, b), max(a, b))]
        return r
    sq, hx, pet = graph_two_cells(adj)
    piv = {}

    def reduce(x):
        while x:
            h = x.bit_length() - 1
            if h in piv:
                x ^= piv[h]
            else:
                return x, h
        return 0, None
    for cyc in sq + hx + pet:
        x, h = reduce(vec(cyc))
        if x:
            piv[h] = x
    for L in range(4, maxlen + 1, 2):
        for cyc in _cycles(adj, L):
            x, _ = reduce(vec(cyc))
            if x:
                return L
    return None


def coloured_adjacency(mask, k, reverse=False):
    """(adj, ecol): adjacency and parallel edge-colour lists.  reverse=True applies the Coxeter-diagram automorphism j -> k-j."""
    verts, edges = colored_graph(mask, k)
    adj = [[] for _ in verts]
    ec = [[] for _ in verts]
    for u, v, c in edges:
        cc = k - c if reverse else c
        adj[u].append(v); ec[u].append(cc)
        adj[v].append(u); ec[v].append(cc)
    return adj, ec
