"""E32 (S3-3) -- does the two-sided suspension lift work for every H_2 mechanism? For each of the 32 Stage-2 law classes (a representative cycle z with its minimal
filling families B_1..B_n), all ordered pairs (a,b) of fillings (including a = b): the lift L_{c_a,c_b}(z) is a 3-cycle (checked), and it is NON-DEGENERATE iff it does not bound in
the complex generated by its own prefix sets P_{z3} (equivalently the empty set is not a minimal filling family).  Diagonal pairs are degenerate for every class (LT-2)."""
import json, os, time
import _path
import lift as Lf
from pk import PK
P6, P7 = PK(6), PK(7)


def run():
    cls = json.load(open(os.path.join(_path.V005S2 if False else os.path.join(_path._vpath.V005S2, "CERTIFICATES", "atlas_v2_classes.json"))))
    out = []
    for ci, c in enumerate(cls):
        zb = int(c["cycle_bits"])
        fams = [int(f) for f in c["families"]]
        P = P6.pz(zb)
        zids = [g for g in range(len(P6.FS)) if zb >> g & 1]
        chains = [Lf.filling_chain(P6, zb, P | F) for F in fams]
        rec = {"class": ci, "z_weight": len(zids), "n_families": len(fams), "pairs": []}
        for a in range(len(fams)):
            for b in range(len(fams)):
                zf = Lf.lam_faces([P6.FS[g] for g in zids], 6) ^ Lf.first([P6.FS[g] for g in chains[a]], 6) ^ Lf.last([P6.FS[g] for g in chains[b]], 6)
                z3 = P7.bits([P7.IDX[f] for f in zf])
                cyc = P7.is_cycle(z3)
                nd = not P7.bounds(z3, P7.pz(z3), 3)
                rec["pairs"].append({"a": a, "b": b, "cycle": cyc, "nondegenerate": nd, "weight": len(zf), "P_size": P7.pz(z3).bit_count()})
        rec["offdiag_nondegenerate"] = sum(1 for p in rec["pairs"] if p["a"] != p["b"] and p["nondegenerate"])
        rec["offdiag_total"] = sum(1 for p in rec["pairs"] if p["a"] != p["b"])
        rec["diag_degenerate_all"] = all(not p["nondegenerate"] for p in rec["pairs"] if p["a"] == p["b"])
        rec["all_cycles"] = all(p["cycle"] for p in rec["pairs"])
        out.append(rec)
        print(ci, rec["n_families"], rec["offdiag_nondegenerate"], "/", rec["offdiag_total"], rec["diag_degenerate_all"], rec["all_cycles"], flush=True)
    return out


if __name__ == "__main__":
    t = time.time()
    r = run()
    summ = {"classes": len(r), "pairs_total": sum(len(x["pairs"]) for x in r), "all_lifted_chains_are_cycles": all(x["all_cycles"] for x in r),
            "diagonal_always_degenerate": all(x["diag_degenerate_all"] for x in r), "offdiag_pairs": sum(x["offdiag_total"] for x in r),
            "offdiag_nondegenerate": sum(x["offdiag_nondegenerate"] for x in r), "classes_with_a_nondegenerate_lift": sum(1 for x in r if x["offdiag_nondegenerate"]), "seconds": round(time.time() - t, 1)}
    json.dump({"summary": summ, "classes": r}, open(os.path.join(_path.ROOT, "RESULTS", "E32_lift_all_classes.json"), "w"), indent=1)
    print(summ)
