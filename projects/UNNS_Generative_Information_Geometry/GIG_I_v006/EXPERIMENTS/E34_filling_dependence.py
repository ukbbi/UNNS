"""E34 (v006-2) -- FILLING-DEPENDENCE: abstract and arithmetic.
Triples (L_{a,b}, L_{a',b}, first(c_a+c_a')) for the two conditional pairs {a,a'} = {0,3},{1,2}.  Abstract: in the complex generated by P_L u P_L' the classes [L],[L'],[L+L'] are all nonzero (so [L] != [L'], both nonzero).
Arithmetic: for a 7-label content with denominators D, A(m) = {I : D(I) | m}.  The triple is realised by some m iff, at m = K = lcm over P_L u P_L', no minimal family of L, of L', or of first(d) lies in A(K)
(monotonicity of A(m), as in AT-2).  Identity role map; candidate contents = those of the E30 census (Lmax from argv, default the stored L30 records) or a fresh scan with labels <= Lmax if argv given."""
import itertools, json, os, sys, time
from math import lcm
import _path
import hole_survival as H, lift as Lf, fi
from pk import PK
from E30_arith import denominators  # local copy (parent E30 is frozen)

P6, P7 = PK(6), PK(7)
S = lambda f: [s for s in range(128) if f >> s & 1]
M = lambda f: sum(1 << s for s in f)


def build():
    z6 = P6.bits(H.Z)
    f6, _ = P6.minimal_families(z6, 2)
    P = P6.pz(z6)
    ch = [set(Lf.filling_chain(P6, z6, P | F)) for F in f6]
    lp = json.load(open(os.path.join(_path._vpath.V005S3, "CERTIFICATES", "lift_pairs.json")))
    pairs = {(p["a"], p["b"]): p for p in lp["pairs"]}
    triples = []
    for (a, a2) in [(0, 3), (3, 0), (1, 2), (2, 1)]:
        d = P6.bits(ch[a] ^ ch[a2])
        e = fi.embed(P6, P7, d, "first")
        fe, st = P7.minimal_families(e, 3)
        for b in range(4):
            if b in (a, a2):
                continue
            p1, p2 = pairs[(a, b)], pairs[(a2, b)]
            z1, z2 = P7.bits(p1["z3_faces"]), P7.bits(p2["z3_faces"])
            assert z1 ^ z2 == e
            Pset = [s for s in range(1, 128) if (P7.pz(z1) | P7.pz(z2)) >> s & 1]
            triples.append({"a": a, "a2": a2, "b": b, "Pset": Pset, "P_L": S(P7.pz(z1)), "fams_L": [M(f) for f in p1["families"]], "fams_Lp": [M(f) for f in p2["families"]],
                            "fams_e": [M(S(f)) for f in fe], "fam_e_sets": [S(f) for f in fe if f.bit_count() < 5]})
    return triples


def survives(D, tr):
    K = 1
    for s in tr["Pset"]:
        K = lcm(K, D[s])
    A = 0
    for s in range(1, len(D)):
        if K % D[s] == 0:
            A |= 1 << s
    fams = tr["fams_L"] + tr["fams_Lp"] + tr["fams_e"]
    return all(f & ~A for f in fams), K


if __name__ == "__main__":
    t = time.time()
    tr = build()
    cand = [tuple(r["content"]) for r in json.load(open(os.path.join(_path._vpath.V005S3, "RESULTS", "E30_arithmetic_census_L30.json")))["records"]]
    hits = []
    for C in cand:
        D = denominators(list(C))
        for k, x in enumerate(tr):
            ok, K = survives(D, x)
            if ok:
                hits.append({"content": list(C), "a": x["a"], "a2": x["a2"], "b": x["b"], "K": str(K)})
    out = {"abstract_triples": [{k: v for k, v in x.items() if k in ("a", "a2", "b", "fam_e_sets")} for x in tr], "candidate_contents": len(cand), "arithmetic_dependence_hits": len(hits),
           "hits": hits[:200], "seconds": round(time.time() - t, 1)}
    json.dump(out, open(os.path.join(_path.ROOT, "RESULTS", "E34_filling_dependence.json"), "w"), indent=1)
    print(len(cand), "candidates;", len(hits), "dependence hits")
    for h in hits[:10]:
        print(h)
