"""E33 (v006-1) -- FILLING-INDEPENDENCE of the two-sided suspension lift.
Chain identities (proved, re-verified here on the anchor cycle):  L_{a',b}+L_{a,b} = first(c_a+c_a'),  L_{a,b'}+L_{a,b} = last(c_b+c_b').
Hence, for any admissible complex A containing the supports of both lifts, [L_{a',b}] = [L_{a,b}] in H_3(K(A)) iff first(d) bounds in K_7(A), d = c_a+c_a'.
Part A (inter-family): d_ij = c_i+c_j for the four Stage-1 fillings; exact P_6 families of d, exact P_7 families of first(d)/last(d) (with completeness certificates).
Part B (intra-family): every filling inside K(P_z u B_i) differs from c_i by a 3-cycle d of K(P_z u B_i) (dim Z_3 = 9,9,25,31).  For B0,B1 all 2^9 differences are tested; for B2,B3 the basis plus 2000 random sums.
Test: does first(d) bound in the complex generated by its own prefix sets (empty minimal family)?  Writes RESULTS/E33_filling_independence.json."""
import itertools, json, os, random, time
import _path
import hole_survival as H, lift as Lf, fi
from pk import PK, verify_family_certificate

P6, P7 = PK(6), PK(7)
S = lambda f: [s for s in range(128) if f >> s & 1]


def run():
    z6 = P6.bits(H.Z)
    f6, _ = P6.minimal_families(z6, 2)
    P = P6.pz(z6)
    ch = [set(Lf.filling_chain(P6, z6, P | F)) for F in f6]
    out = {"partA": [], "partB": [], "identity_checks": {}}
    # --- identity checks on all (a,a',b),(a,b,b')
    ok_first = ok_last = True
    cache = {}
    def L(a, b):
        if (a, b) not in cache:
            zf = Lf.lam_faces([P6.FS[g] for g in H.Z], 6) ^ Lf.first([P6.FS[g] for g in ch[a]], 6) ^ Lf.last([P6.FS[g] for g in ch[b]], 6)
            cache[(a, b)] = P7.bits([P7.IDX[f] for f in zf])
        return cache[(a, b)]
    for a, a2, b in itertools.product(range(4), repeat=3):
        d = P6.bits(ch[a] ^ ch[a2])
        ok_first &= (L(a, b) ^ L(a2, b)) == fi.embed(P6, P7, d, "first")
        ok_last &= (L(b, a) ^ L(b, a2)) == fi.embed(P6, P7, d, "last")
    out["identity_checks"] = {"L_a'b + L_ab = first(c_a+c_a')": ok_first, "L_ba + L_ba' = last(c_a+c_a')": ok_last, "triples": 64}
    # --- Part A
    for i, j in itertools.combinations(range(4), 2):
        d = P6.bits(ch[i] ^ ch[j])
        fd, _ = P6.minimal_families(d, 3)
        rec = {"i": i, "j": j, "weight": bin(d).count("1"), "P6_family_sizes": sorted(x.bit_count() for x in fd), "P6_families": [S(x) for x in fd]}
        for kind in ("first", "last"):
            e = fi.embed(P6, P7, d, kind)
            fams, st = P7.minimal_families(e, 3, certificate=True)
            ok, msg = verify_family_certificate(P7, e, 3, fams, st["maximal_false_sets"])
            rec[kind + "_family_sizes"] = sorted(x.bit_count() for x in fams)
            rec[kind + "_families"] = [S(x) for x in fams]
            rec[kind + "_certified"] = ok
        # sigma-correspondence: P6 family F  ->  F | {rank-6 marker 64}
        sig = {frozenset(s | 64 for s in S(x)) for x in fd}
        rec["sigma_of_P6_families_are_P7_families"] = all(any(frozenset(S(y)) == t for y in fams) for t in sig) if kind == "last" else None
        fF, _ = P7.minimal_families(fi.embed(P6, P7, d, "first"), 3)
        rec["sigma_first_check"] = all(any(frozenset(S(y)) == t for y in fF) for t in sig)
        rec["self_bounding"] = 0 in fd
        out["partA"].append(rec)
        print("A", i, j, rec["P6_family_sizes"], rec["first_family_sizes"], rec["sigma_first_check"], flush=True)
    # --- Part B
    random.seed(20261106)
    for i, F in enumerate(f6):
        basis = fi.cycle_basis(P6, P | F, 3)
        n = len(basis)
        exhaustive = n <= 9
        if exhaustive:
            subsets = range(1, 1 << n)
        else:
            subsets = list(1 << k for k in range(n)) + [random.getrandbits(n) or 1 for _ in range(2000)]
        tested = failed = 0
        fail_examples = []
        for m in subsets:
            d = 0
            for k in range(n):
                if m >> k & 1:
                    d ^= basis[k]
            e = fi.embed(P6, P7, d, "first")
            tested += 1
            if not P7.bounds(e, P7.pz(e), 3):
                failed += 1
                if len(fail_examples) < 3:
                    fail_examples.append(m)
        rec = {"family": i, "dimZ3": n, "exhaustive": exhaustive, "tested": tested, "first_d_not_self_bounding": failed, "examples_mask": fail_examples}
        out["partB"].append(rec)
        print("B", rec, flush=True)
    return out


if __name__ == "__main__":
    t = time.time()
    r = run()
    r["seconds"] = round(time.time() - t, 1)
    json.dump(r, open(os.path.join(_path.ROOT, "RESULTS", "E33_filling_independence.json"), "w"), indent=1)
    print(r["identity_checks"], r["seconds"])
