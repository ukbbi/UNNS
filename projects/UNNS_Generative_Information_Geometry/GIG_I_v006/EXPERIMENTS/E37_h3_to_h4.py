"""E37 (v006-5) -- controlled H_3 -> H_4 lift in P_8 (ONE base pair, exact GF(2)).
Base: the Stage-3 lifted 3-cycle w = L_{a,b}(z) in P_7 with two of its own minimal filling families G, G' (4-chains c, c' in K(P_w u G), K(P_w u G') with boundary w).
Second lift:  L2 = Lam(w) + first(c) + last(c')  in P_8 (new rank 7).  Tests: L2 is a 4-cycle (chain level; the boundary lemma is dimension-free); diagonal L2(c,c) bounds; off-diagonal L2 is
non-degenerate iff it does not bound in the complex generated by its own prefix sets P_{L2}.  No cohomological certificate by minimal-family dualisation is attempted in P_8 (family lattice too large)."""
import json, os, sys, time
import _path
import lift as Lf, fi
from pk import PK

P6, P7 = PK(6), PK(7)
t0 = time.time()
P8 = PK(8)
lp = json.load(open(os.path.join(_path._vpath.V005S3, "CERTIFICATES", "lift_pairs.json")))
PAIRS = {(p["a"], p["b"]): p for p in lp["pairs"]}


def second_lift(pair, i, j):
    w = P7.bits(PAIRS[pair]["z3_faces"])
    Pw = P7.pz(w)
    fams = PAIRS[pair]["families"]
    Gm = [sum(1 << s for s in f) for f in fams]
    chains = []
    for g in (i, j):
        B = fi.Bounder(P7, Pw | Gm[g], 3)
        c = B.express(w)
        assert c is not None
        chains.append(c)
    faces = Lf.lam_faces([P7.FS[g] for g in fi.ids_of(w)], 7) ^ Lf.first([P7.FS[g] for g in chains[0]], 7) ^ Lf.last([P7.FS[g] for g in chains[1]], 7)
    ids = [P8.IDX[f] for f in faces]
    return P8.bits(ids), len(chains[0]), len(chains[1])


if __name__ == "__main__":
    out = {"P8_faces": len(P8.FS), "build_seconds": round(time.time() - t0, 1), "records": []}
    todo = [((0, 1), 0, 1), ((0, 1), 0, 0), ((0, 1), 1, 0), ((0, 1), 0, 2)]
    for pair, i, j in todo:
        t = time.time()
        l2, na, nb = second_lift(pair, i, j)
        cyc = P8.is_cycle(l2)
        Pl = P8.pz(l2)
        nd = None
        if cyc:
            B = fi.Bounder(P8, Pl, 4)
            nd = not B.contains(l2)
        rec = {"base_pair": list(pair), "fill_idx": [i, j], "weight": bin(l2).count("1"), "chain_sizes": [na, nb], "is_4cycle": cyc, "P_L2_size": Pl.bit_count(),
               "bounds_in_own_complex": (None if nd is None else (not nd)), "nondegenerate": nd, "seconds": round(time.time() - t, 1)}
        out["records"].append(rec)
        print(rec, flush=True)
    json.dump(out, open(os.path.join(_path.ROOT, "RESULTS", "E37_h3_to_h4.json"), "w"), indent=1)
