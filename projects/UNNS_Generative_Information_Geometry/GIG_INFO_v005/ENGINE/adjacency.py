"""GIG-INFO v005 -- adjacency-cover of the forbidden complex for pairwise-transition systems (k=6).
A history is a full flag; it contains the adjacency (x,y) iff x is immediately followed by y.  For an ordered pair p=(x,y) let Z_p = subcomplex of T generated by the flags containing adjacency p.
A chain of cuts sigma <-> ordered partition (B_1|...|B_m), m>=2, b(.) = block index.  sigma is a face of a flag with adjacency (x,y) iff b(y)-b(x) in {0,1}.
Hence Z_S := intersection of Z_p, p in S, has the simplices  {ordered partitions with b(y)-b(x) in {0,1} for all (x,y) in S}."""
import itertools
import _vpath  # noqa: F401
import forbidden as fb

K = 6
PAIRS = [(x, y) for x in range(K) for y in range(K) if x != y]


def ordered_partitions():
    """list of block-index tuples b (length K, values 1..m, surjective), m>=2"""
    out = []
    for m in range(2, K + 1):
        for b in itertools.product(range(1, m + 1), repeat=K):
            if len(set(b)) == m:
                out.append(b)
    return out


OP = ordered_partitions()


def cuts(b):
    m = max(b)
    return tuple(sum(1 << i for i in range(K) if b[i] <= t) for t in range(1, m))


def Z_S_sim(S):
    sim = {}
    for b in OP:
        if all((b[y] - b[x]) in (0, 1) for x, y in S):
            c = cuts(b)
            sim.setdefault(len(c) - 1, []).append(c)
    return {d: sorted(L) for d, L in sim.items()}


def Z_S_betti(S, top=2):
    sim = Z_S_sim(S)
    if not sim:
        return None
    return fb.reduced_betti(sim, top)


def Y_from_adjacency(Bpairs):
    """simplices (as set of chain tuples, all dims) of union of Z_p over p in Bpairs"""
    out = set()
    for b in OP:
        if any((b[y] - b[x]) in (0, 1) for x, y in Bpairs):
            out.add(cuts(b))
    # faces of a simplex are coarsenings, already contained (closure property); return per-dim dict
    sim = {}
    for c in out:
        sim.setdefault(len(c) - 1, []).append(c)
    return {d: sorted(L) for d, L in sim.items()}


def hamiltonian_mask(allowed):
    """mask of orderings (hc.perms order) all of whose consecutive pairs lie in the allowed set of ordered pairs"""
    import history_complex as hc
    m = 0
    for i, p in enumerate(hc.perms(K)):
        if all((p[j], p[j + 1]) in allowed for j in range(K - 1)):
            m |= 1 << i
    return m
