"""GIG-INFO v004 -- the forbidden-flag complex Y_A and Alexander duality.
A history = full flag of proper subsets (its prefix sets).  For a set A of histories (vertices of P_k), Y_A is the simplicial complex on the proper non-empty subsets of {0..k-1} generated by the chains of the NON-admissible histories.
Theorem T-AD (proved in THEORY): for A != all, K_A ~ S^{k-2} minus |Y_A|, hence reduced H_j(K_A) = reduced H^{k-3-j}(Y_A) over GF(2); for k=6: beta_2(K_A) = dim H_1(Y_A)."""
import itertools
import _vpath  # noqa: F401
import history_complex as hc


def prefix_chains(k):
    out = []
    for p in hc.perms(k):
        m, ch = 0, []
        for x in p[:-1]:
            m |= 1 << x
            ch.append(m)
        out.append(tuple(ch))
    return out


_PC = {}


def chains(k):
    if k not in _PC:
        _PC[k] = prefix_chains(k)
    return _PC[k]


def gf2_rank(rows):
    piv, rk = {}, 0
    for r in rows:
        while r:
            h = r.bit_length() - 1
            if h in piv:
                r ^= piv[h]
            else:
                piv[h] = r; rk += 1; break
    return rk


def y_simplices(A_mask, k):
    """dict dim -> sorted list of simplices (tuples of subset-bitmasks) of Y_A."""
    sim = {}
    for i, ch in enumerate(chains(k)):
        if A_mask >> i & 1:
            continue
        for r in range(1, len(ch) + 1):
            for sub in itertools.combinations(ch, r):
                sim.setdefault(r - 1, set()).add(sub)
    return {d: sorted(s) for d, s in sim.items()}


def reduced_betti(sim, top):
    """reduced GF(2) Betti numbers b~_0..b~_top of the simplicial complex given by sim (augmented with the empty simplex)."""
    idx = {d: {s: i for i, s in enumerate(L)} for d, L in sim.items()}
    f = {d: len(L) for d, L in sim.items()}
    f[-1] = 1
    rk = {}
    for d in range(0, top + 2):
        if d not in sim:
            rk[d] = 0; continue
        rows = []
        for s in sim[d]:
            if d == 0:
                rows.append(1)
            else:
                r = 0
                for j in range(len(s)):
                    r ^= 1 << idx[d - 1][s[:j] + s[j + 1:]]
                rows.append(r)
        rk[d] = gf2_rank(rows)
    rk[-1] = 0
    return [f.get(d, 0) - rk.get(d, 0) - rk.get(d + 1, 0) for d in range(0, top + 1)]
