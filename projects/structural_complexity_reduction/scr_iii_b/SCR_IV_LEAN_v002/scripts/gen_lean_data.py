#!/usr/bin/env python3
"""SCR-IV data generator (deterministic). Reads the frozen instance and writes SCR_IV_Data.lean, data/coeff_bits.csv, data/instance_manifest.json.
Coefficient provenance: text token -> IEEE-754 binary64 (Python float(), correctly rounded, identical to the C++ solver's stream extraction)
-> exact dyadic rational via float.as_integer_ratio(). No coefficient is rounded again. usage: gen_lean_data.py ROOT"""
import sys, struct, json, hashlib, pathlib
from fractions import Fraction
ROOT = pathlib.Path(sys.argv[1]); src = ROOT/"data/real_4x4.txt"; raw = src.read_bytes(); t = raw.decode().split()
n, nv = int(t[0]), int(t[1]); assert (n, nv) == (40, 16)
toks = t[2:2+n*(n-1)//2]; vt = t[2+n*(n-1)//2:]; assert len(toks) == 780 and len(vt) == 2*nv
vals = []; rows_tok = []; c = 0
for i in range(n):
    rows_tok.append(toks[c:c+n-1-i]); c += n-1-i
fr = [[Fraction(float(x)) for x in r] for r in rows_tok]
for r in fr:
    for q in r: assert (q.denominator & (q.denominator-1)) == 0          # dyadic
S = max(q.denominator.bit_length()-1 for r in fr for q in r)
num = [[int(q*(1 << S)) for q in r] for r in fr]
for r, rr in zip(fr, num):
    for q, m in zip(r, rr): assert Fraction(m, 1 << S) == q
def dy(x):
    q = Fraction(x); k = q.denominator.bit_length()-1; assert q.denominator == 1 << k; return q.numerator, k
verts = [(int(vt[2*v]), int(vt[2*v+1])) for v in range(nv)]
rep = {"ground": dy(-0.16364841082886986), "nongr": dy(-0.1534031680911189)}
A = dy(1.0095767595046513e-18)
lines = ["-- GENERATED by scripts/gen_lean_data.py from data/real_4x4.txt. Do not edit by hand.", "namespace SCR_IV", "",
 "/-- sha256 of data/real_4x4.txt (informational; Lean cannot hash files). -/", 'def instanceSha256 : String := "%s"' % hashlib.sha256(raw).hexdigest(), "",
 "/-- Common power-of-two denominator: every coupling is kRows[i][j-i-1] / 2^kShift, exactly. -/", "def kShift : Nat := %d" % S, "",
 "/-- Row i holds the numerators of K_{i,j} for j = i+1 .. 39 (upper triangle, 780 entries). -/", "def kRows : List (List Int) := ["]
for i, r in enumerate(num):
    lines.append("  [" + ", ".join(str(m) for m in r) + "]" + ("," if i < n-1 else ""))
lines += ["]", "", "/-- (vertex island mask, plus-in mask) for the 16 frozen constrained vertices, in file order. -/", "def vertices : List (Nat × Nat) := ["]
lines += ["  (%d, %d)%s" % (m, p, "," if k < nv-1 else "") for k, (m, p) in enumerate(verts)] + ["]", ""]
def Hnum(idv):
    sg = [1 if (idv >> i) & 1 else -1 for i in range(n)]
    return sum(num[i][j-i-1]*sg[i]*sg[j] for i in range(n) for j in range(i+1, n))
G_ID, N_ID = 711243241830, 161487427942
lines += ["/-- CLAIMED exact scaled energies (independent Python exact-integer arithmetic). They are NOT trusted: SCR_IV_Witness proves them in the Lean kernel. -/",
 "def claimedGroundNum : Int := %d" % Hnum(G_ID), "def claimedNonGNum : Int := %d" % Hnum(N_ID), ""]
lines += ["/-- Reported solver energies (A units) as exact dyadic rationals num / 2^shift (the doubles printed in GAP4_FIRST_RUN.jsonl). -/",
 "def reportedGround : Int × Nat := (%d, %d)" % rep["ground"], "def reportedNonG : Int × Nat := (%d, %d)" % rep["nongr"], "",
 "/-- A(792 K) = 1.0095767595046513e-18 J, the frozen v005 double, as an exact dyadic rational. -/", "def aJoule : Int × Nat := (%d, %d)" % A, "", "end SCR_IV", ""]
(ROOT/"SCR_IV_Data.lean").write_text("\n".join(lines))
with open(ROOT/"data/coeff_bits.csv", "w") as f:
    f.write("i,j,token,binary64_hex,numerator_over_2^kShift\n"); k = 0
    for i in range(n):
        for j in range(i+1, n):
            tok = rows_tok[i][j-i-1]; f.write("%d,%d,%s,%s,%d\n" % (i, j, tok, struct.pack(">d", float(tok)).hex(), num[i][j-i-1]))
man = dict(source="data/real_4x4.txt", sha256=hashlib.sha256(raw).hexdigest(), spins=n, vertices=nv, couplings=780, kShift=S,
           max_abs_numerator_bits=max(abs(m).bit_length() for r in num for m in r), sum_abs_K_exact=str(sum(abs(q) for r in fr for q in r)),
           note="SCR-III instance, frozen; original PROVENANCE: GAP4_v010/output/real_4x4.txt (sha 3d47ed12...). Not modified.")
(ROOT/"data/instance_manifest.json").write_text(json.dumps(man, indent=1)+"\n")
print(json.dumps(man))
