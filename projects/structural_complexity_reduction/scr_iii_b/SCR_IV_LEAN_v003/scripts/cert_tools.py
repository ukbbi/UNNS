#!/usr/bin/env python3
"""IV-4A certificate TOOLS (NOT part of the trusted base). Encodes a proof tree in the checker's format and emits Lean test files.
  toy      : tiny random instances, valid certificates + tampered/negative variants      (tests/toy_cert.lean, tests/neg_cert_*.lean)
  calib    : a SMALL SUBTREE of the real instance (prefix = first D0 bits of the ground witness), used ONLY to time the kernel checker.
             It is not a global certificate and proves nothing about the 4x4 optimum.
usage: cert_tools.py ROOT toy|calib [D0]"""
import sys
sys.set_int_max_str_digits(0)
import random, pathlib, itertools
from fractions import Fraction
ROOT = pathlib.Path(sys.argv[1]); mode = sys.argv[2]

def sabs(l): return sum(abs(x) for x in l)
def gen(R, n, U, leafOK, d, acc, F, T, bits, out, limit=10**7):
    """Pre-order proof tree identical to the checker's recursion. Returns False if no valid subtree exists (some leaf has H < U)."""
    if len(out) > limit: raise RuntimeError("node limit")
    if U <= acc - sabs(F) - T: out.append(0); return True
    if d == n:
        if leafOK(bits): out.append(2); return True
        return False
    out.append(1)
    f, fs = F[0], F[1:]
    row = R[d]; Tn = T - sabs(row)
    ok = gen(R, n, U, leafOK, d+1, acc - f, [a - r for a, r in zip(fs, row)], Tn, bits, out, limit)
    ok = ok and gen(R, n, U, leafOK, d+1, acc + f, [a + r for a, r in zip(fs, row)], Tn, bits | (1 << d), out, limit)
    return ok
def encode(tokens):
    c = 0
    for k, t in enumerate(tokens): c |= t << (2*k)
    return c | (1 << (2*len(tokens)))      # sentinel
def root(R, n): return 0, [0]*n, sum(sabs(R[j]) for j in range(n))
def energy(n, R, s):
    return sum(R[i][j-i-1]*s[i]*s[j] for i in range(n) for j in range(i+1, n))
def spins(b, n): return [1 if (b >> i) & 1 else -1 for i in range(n)]

if mode == "toy":
    rng = random.Random(4242); outs = []
    for t in range(4):
        n = rng.randint(4, 7)
        R = [[rng.randint(-9, 9) for _ in range(n-d-1)] for d in range(n)]
        Hs = {b: energy(n, R, spins(b, n)) for b in range(1 << n)}
        U = min(Hs.values()); acc, F, T = root(R, n)
        tok = []; assert gen(R, n, U, lambda b: False, 0, acc, F, T, 0, tok)
        outs.append((n, R, U, encode(tok), len(tok)))
        tok2 = []; assert not gen(R, n, U+1, lambda b: False, 0, acc, F, T, 0, tok2)   # U+1 is not a valid lower bound: generator refuses
    # leaf-mode toy: objective = ids b < 5 only; leafOK b := (5 <= b)
    no = 6; Ro = [[rng.randint(-9, 9) for _ in range(no-d-1)] for d in range(no)]
    Uo = min(energy(no, Ro, spins(b, no)) for b in range(1 << no) if b < 5); acc, F, T = root(Ro, no)
    tok = []; assert gen(Ro, no, Uo, lambda b: b >= 5, 0, acc, F, T, 0, tok); assert 2 in tok
    lines = ["import SCR_IV_CertReal", "open SCR_IV", "/-! TOY end-to-end tests of the checker (generated by scripts/cert_tools.py toy). MUST compile. -/"]
    for k, (n, R, U, c, nt) in enumerate(outs):
        lines += [f"def R{k} (d : Nat) : List Int := {R}.getD d []", f"theorem toy{k}_ok : checkAll R{k} {n} ({U}) (fun _ => false) {c} = true := by decide +kernel",
                  f"theorem toy{k}_lower_bound_attained : checkAll R{k} {n} ({U+1}) (fun _ => false) {c} = false := by decide +kernel"]
    lines += [f"def Rodd (d : Nat) : List Int := {Ro}.getD d []", f"theorem toy_odd_ok : checkAll Rodd {no} ({Uo}) (fun b => decide (5 ≤ b)) {encode(tok)} = true := by decide +kernel",
              f"theorem toy_odd_wrong_leaf : checkAll Rodd {no} ({Uo}) (fun b => decide (b < 5)) {encode(tok)} = false := by decide +kernel"]
    (ROOT/"tests/toy_cert.lean").write_text("\n".join(lines)+"\n")
    # negative controls (each claims a false acceptance and must be rejected by the kernel)
    n, R, U, c, nt = outs[0]
    H = "import SCR_IV_CertReal\nopen SCR_IV\n/-- NEGATIVE CONTROL: this file MUST FAIL to compile. -/\n"
    def neg(name, body): (ROOT/f"tests/neg_cert_{name}.lean").write_text(H + f"def R0 (d : Nat) : List Int := {R}.getD d []\n" + body + "\n")
    neg("U_plus1", f"theorem bad : checkAll R0 {n} ({U+1}) (fun _ => false) {c} = true := by decide +kernel")
    neg("tampered", f"theorem bad : checkAll R0 {n} ({U}) (fun _ => false) {c ^ (1 << 0)} = true := by decide +kernel")      # token 0 changed
    neg("truncated", f"theorem bad : checkAll R0 {n} ({U}) (fun _ => false) {c >> 2} = true := by decide +kernel")
    neg("trailing", f"theorem bad : checkAll R0 {n} ({U}) (fun _ => false) {c | (1 << (2*nt+2))} = true := by decide +kernel")
    neg("wrong_rows", f"theorem bad : checkAll (fun d => (R0 d).map (fun x => x + 1)) {n} ({U}) (fun _ => false) {c} = true := by decide +kernel")
    print("toy tests written; node counts:", [o[4] for o in outs])

elif mode == "calib":
    D0 = int(sys.argv[3]); t = (ROOT/"data/real_4x4.txt").read_text().split(); n = 40; c = 2
    K = [[0]*n for _ in range(n)]
    for i in range(n):
        for j in range(i+1, n):
            fr = Fraction(float(t[c])) * (1 << 70); assert fr.denominator == 1; K[i][j] = int(fr); c += 1
    R = [[K[d][j] for j in range(d+1, n)] for d in range(n)]
    gb = 711243241830; U = -193201942568284180326
    p = spins(gb, n)[:D0]; bits0 = gb & ((1 << D0) - 1)
    acc = sum(K[i][j]*p[i]*p[j] for i in range(D0) for j in range(i+1, D0))
    F = [sum(K[i][j]*p[i] for i in range(D0)) for j in range(D0, n)]
    T = sum(sabs(R[j]) for j in range(D0, n))
    tok = []; ok = gen(R, n, U, lambda b: False, D0, acc, F, T, bits0, tok, limit=300000)
    cert = encode(tok)
    (ROOT/f"tests/calib_{D0}.lean").write_text(
        "import SCR_IV_CertReal\nopen SCR_IV\n/-! CALIBRATION ONLY: a subtree of the real instance. Not a global certificate. -/\n"
        f"theorem calib : chk Rreal ({U}) (fun _ => false) {cert} {n-D0} {D0} 0 ({acc}) {F} ({T}) {bits0} = some {2*len(tok)} := by decide +kernel\n")
    print(f"D0={D0} subtree nodes={len(tok)} valid={ok} cert_bits={2*len(tok)+2} splits={tok.count(1)} prunes={tok.count(0)}")

def real_instance():
    t = (ROOT/"data/real_4x4.txt").read_text().split(); n = 40; c = 2
    K = [[0]*n for _ in range(n)]
    for i in range(n):
        for j in range(i+1, n):
            fr = Fraction(float(t[c])) * (1 << 70); assert fr.denominator == 1; K[i][j] = int(fr); c += 1
    return n, [[K[d][j] for j in range(d+1, n)] for d in range(n)]
def state_at(R, n, b, d):
    acc, F, T = root(R, n)
    for k in range(d):
        v = 1 if (b >> k) & 1 else -1; f, fs = F[0], F[1:]
        acc, F, T = acc + v*f, [a + v*r for a, r in zip(fs, R[k])], T - sabs(R[k])
    return acc, F, T
def sub_cert(R, n, U, leafOK, d, b, limit=10**6):
    acc, F, T = state_at(R, n, b, d); tok = []
    ok = gen(R, n, U, leafOK, d, acc, F, T, b, tok, limit)
    return ok, tok

if mode == "toypart":
    rng = random.Random(777); n = 8; D0 = 3
    R = [[rng.randint(-9, 9) for _ in range(n-d-1)] for d in range(n)]
    U = min(energy(n, R, spins(b, n)) for b in range(1 << n))
    cs = []
    for b in range(1 << D0):
        ok, tok = sub_cert(R, n, U, lambda x: False, D0, b); assert ok; cs.append(encode(tok))
    bs = [cs[:3], cs[3:5], cs[5:]]
    lines = ["import SCR_IV_CertReal", "open SCR_IV", "/-! TOY partitioned certificate (generated by scripts/cert_tools.py toypart): 2^3 frontier prefixes in 3 batches. MUST compile. -/",
             f"def Rp (d : Nat) : List Int := {R}.getD d []"]
    lo = 0
    for j, c in enumerate(bs):
        lines.append(f"theorem pbatch{j} : batchOK Rp {n} ({U}) (fun _ => false) {D0} {lo} {c} = true := by decide +kernel"); lo += len(c)
    lines.append(f"theorem pall : batchesOK Rp {n} ({U}) (fun _ => false) {D0} 0 {bs} = true := by decide +kernel")
    lines.append(f"theorem pcover : ∀ b, b < 2 ^ {D0} → subOK Rp {n} ({U}) (fun _ => false) {D0} b ({bs}.flatten.getD b 0) = true :=\n  batches_cover pall (by decide)")
    lines.append(f"theorem p_U_plus1_rejected : batchesOK Rp {n} ({U+1}) (fun _ => false) {D0} 0 {bs} = false := by decide +kernel")
    (ROOT/"tests/toy_part.lean").write_text("\n".join(lines)+"\n")
    (ROOT/"tests/neg_cert_part_U_plus1.lean").write_text("import SCR_IV_CertReal\nopen SCR_IV\n/-- NEGATIVE CONTROL: this file MUST FAIL to compile. -/\n"
        f"def Rp (d : Nat) : List Int := {R}.getD d []\ntheorem bad : batchesOK Rp {n} ({U+1}) (fun _ => false) {D0} 0 {bs} = true := by decide +kernel\n")
    (ROOT/"tests/neg_cert_part_gap.lean").write_text("import SCR_IV_CertReal\nopen SCR_IV\n/-- NEGATIVE CONTROL: this file MUST FAIL to compile (batches do not cover 2^3 prefixes). -/\n"
        f"def Rp (d : Nat) : List Int := {R}.getD d []\ntheorem bad : ({bs[:2]}.flatten.length = 2 ^ {D0}) := by decide\n")
    print("toypart written; tokens per prefix:", [len(sub_cert(R, n, U, lambda x: False, D0, b)[1]) for b in range(1 << D0)])

elif mode == "calibpart":
    D0 = int(sys.argv[3]); cnt = int(sys.argv[4]); n, R = real_instance()
    gb = 711243241830; U = -193201942568284180326; rng = random.Random(99)
    bl = [gb & ((1 << D0) - 1)] + [rng.getrandbits(D0) for _ in range(cnt-1)]
    cs = []; tot = 0
    for b in bl:
        ok, tok = sub_cert(R, n, U, lambda x: False, D0, b); assert ok; cs.append(encode(tok)); tot += len(tok)
    lines = ["import SCR_IV_CertReal", "open SCR_IV", "/-! CALIBRATION ONLY: independent frontier prefix checks on the real instance (subOK). Not a global certificate. -/"]
    for j, (b, c) in enumerate(zip(bl, cs)):
        lines.append(f"theorem fp{j} : subOK Rreal 40 ({U}) (fun _ => false) {D0} {b} {c} = true := by decide +kernel")
    (ROOT/f"tests/calibpart_{D0}.lean").write_text("\n".join(lines)+"\n")
    print(f"D0={D0} prefixes={bl[:3]}... total tokens={tot}")
