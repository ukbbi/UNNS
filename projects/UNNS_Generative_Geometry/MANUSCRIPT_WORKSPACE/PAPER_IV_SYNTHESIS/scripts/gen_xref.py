"""Builds tex/xref.tex (macro \\Src{paper}{label} -> 'Paper III, Theorem 3.4') and results/theorem_index.json from the v0.4 .aux/.prov/.tex of Papers I-III."""
import re, glob, json, os
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Location of Papers I-III (v0.4 trees): $UNNS_PAPERS_ROOT, else the sibling layout MANUSCRIPT_WORKSPACE/PAPER_*/v0.4.
R = os.environ.get('UNNS_PAPERS_ROOT') or os.path.normpath(os.path.join(H, '..', '..')) + '/'
if not R.endswith('/'): R += '/'
roots = {'I': R+'PAPER_I_TRANSPORT/v0.4/tex', 'II': R+'PAPER_II_HISTORIES/v0.4/tex', 'III': R+'PAPER_III_EVOLUTION/v0.4/tex'}
names = {'thm': 'Theorem', 'prop': 'Proposition', 'lem': 'Lemma', 'cor': 'Corollary', 'def': 'Definition'}
if not os.path.isdir(R+'PAPER_I_TRANSPORT/v0.4/tex'):
    # portable fallback: the package ships the generated tex/xref.tex, results/theorem_index.json and results/source_uid_index.json
    assert os.path.exists(H+'/tex/xref.tex') and os.path.exists(H+'/results/theorem_index.json'), 'Papers I-III not found; set UNNS_PAPERS_ROOT'
    print('Papers I-III sources not present: using shipped tex/xref.tex and results/theorem_index.json (NOT regenerated)'); raise SystemExit(0)
idx = {}; lines = []
for P, d in roots.items():
    aux = open(d+'/main.aux').read()
    num = {m.group(1): m.group(2) for m in re.finditer(r'\\newlabel\{([^}@]+)\}\{\{([0-9A-Z.]+)\}', aux)}
    prov = {}
    for m in re.finditer(r'\\provrow\{([^}]*)\}\{([^}]*)\}\{([^}]*)\}\{([^}]*)\}\{([^}]*)\}\{([^}]*)\}', open(d+'/main.prov').read()):
        prov.setdefault(m.group(6), []).append(dict(uid=m.group(1), sid=m.group(2), status=m.group(3), treat=m.group(4)))
    for lab, n in num.items():
        kind = lab.split(':')[0]
        if kind not in names: continue
        idx.setdefault(P, {})[lab] = dict(number=n, kind=names[kind], prov=prov.get(n, []))
        key = f"{P}-{lab}"
        lines.append(f"\\expandafter\\def\\csname xr@{key}\\endcsname{{{names[kind]}~{n}}}")
json.dump(idx, open(H+'/results/theorem_index.json', 'w'), indent=1)
hdr = "% generated by scripts/gen_xref.py from the v0.4 .aux and .prov files of Papers I-III\n"
mac = r"""\newcommand{\Src}[2]{\@ifundefined{xr@#1-#2}{\textbf{??}\PackageWarning{xref}{missing source #1 #2}}{Paper~#1, \csname xr@#1-#2\endcsname}}
"""
open(H+'/tex/xref.tex', 'w').write(hdr+"\\makeatletter\n"+"\n".join(lines)+"\n"+mac.replace('#1-#2', '#1-#2')+"\\makeatother\n")
print({k: len(v) for k, v in idx.items()})

uids = {}
for P, sub_ in (('I', 'PAPER_I_TRANSPORT'), ('II', 'PAPER_II_HISTORIES'), ('III', 'PAPER_III_EVOLUTION')):
    u = set()
    for f in glob.glob(R+sub_+'/v0.4/crosswalk/*'):
        if os.path.isfile(f): u |= set(re.findall(r'CW-\d{4}', open(f, errors='ignore').read()))
    uids[P] = sorted(u)
json.dump(uids, open(H+'/results/source_uid_index.json', 'w'), indent=0)
print('source UIDs:', {k: len(v) for k, v in uids.items()})
