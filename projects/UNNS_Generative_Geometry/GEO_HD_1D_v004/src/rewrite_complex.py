"""HD-1D v004 builder: the extended (cubical) rewrite complex of the histories of a fixed source.

Atomic moves of a history w (a word):  a swap of two adjacent distinct labels (interval of length 2), or a block replacement u -> v
(interval of length |u|) along a given move.  A *cube* is a set of d atomic moves with pairwise disjoint intervals such that all 2^d
words obtained by applying any subset are admissible from the source.  Cubes are identified with their vertex sets.  The complex is the
cubical set generated by these cubes (vertices = admissible histories; edges = legal moves; squares/cubes = independent moves).
It is NOT the permutohedral complex: braid hexagons are not filled (repeated labels have no permutohedral construction in v003)."""
from itertools import combinations
from block_rewrites import admissible, word_arrangements, move_blocks


def atomic_moves(w, m, blocks):
    """list of (start, old_len, new_word) legal single moves at w"""
    out = []
    for i in range(len(w) - 1):
        if w[i] != w[i + 1]:
            w2 = (w[i + 1], w[i])
            if admissible(m, w[:i] + w2 + w[i + 2:]): out.append((i, 2, w2))
    for L, Rw in blocks:
        for A, B in ((L, Rw), (Rw, L)):
            Aset = set(A); la = len(A[0])
            for i in range(len(w) - la + 1):
                if w[i:i + la] in Aset:
                    for v in B:
                        if admissible(m, w[:i] + v + w[i + la:]): out.append((i, la, v))
    return out


def apply_set(w, moves):
    """apply pairwise disjoint moves (right to left)"""
    for (i, l, v) in sorted(moves, key=lambda t: -t[0]): w = w[:i] + v + w[i + l:]
    return w


def build_cubes(words, m, blocks, maxdim=4):
    """cells: dict dim -> set of frozenset(vertex words)"""
    Wset = set(words); cells = {0: {frozenset([w]) for w in words}}
    for w in words:
        mv = [t for t in atomic_moves(w, m, blocks) if apply_set(w, [t]) in Wset]
        for d in range(1, maxdim + 1):
            for S in combinations(mv, d):
                iv = sorted((t[0], t[0] + t[1]) for t in S)
                if any(iv[k][1] > iv[k + 1][0] for k in range(len(iv) - 1)): continue
                verts = [apply_set(w, [S[k] for k in range(d) if (mask >> k) & 1]) for mask in range(1 << d)]
                if all(admissible(m, x) and x in Wset for x in verts) and len(set(verts)) == (1 << d):
                    cells.setdefault(d, set()).add(frozenset(verts))
    return cells


def gf2_rank(rows):
    piv = {}; rk = 0
    for r in rows:
        while r:
            h = r.bit_length() - 1
            if h in piv: r ^= piv[h]
            else: piv[h] = r; rk += 1; break
    return rk


def betti(cells):
    """GF(2) Betti numbers of the cubical set; the boundary of a cube is read off its vertex set: a facet is the vertex subset on which one coordinate is fixed.
    To recover coordinates we rebuild each cube's structure from its vertex set by pairing vertices (via the adjacency of cells of dimension d-1 contained in it)."""
    dims = sorted(cells); idx = {d: {c: i for i, c in enumerate(sorted(cells[d], key=lambda s: sorted(s)))} for d in dims}
    rk = {0: 0}
    for d in dims:
        if d == 0: continue
        rows = []
        for c in idx[d]:
            facets = [f for f in cells[d - 1] if f < c]
            m = 0
            for f in facets: m ^= 1 << idx[d - 1][f]
            rows.append(m)
        rk[d] = gf2_rank(rows)
    top = max(dims); out = []
    for d in range(top + 1):
        out.append(len(cells[d]) - rk.get(d, 0) - rk.get(d + 1, 0))
    return tuple(out)
