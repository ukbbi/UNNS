"""Relation lattices Lambda_b = ker(chi_b), orders, subgroup H_b, rectangularity (spec 3).  Standard library only."""
from itertools import product
from math import gcd


def order(p, b):
    if b == 1:
        return 1
    if gcd(p, b) != 1:
        raise ValueError("p not invertible mod b")
    r, k = p % b, 1
    while r != 1:
        r = r * p % b
        k += 1
    return k


def orders(P, b):
    return tuple(order(p, b) for p in P)


def subgroup(P, b):
    """H_b = <p_i> in (Z/b)^x as a set (closure)."""
    H = {1 % b}
    frontier = [1 % b]
    while frontier:
        h = frontier.pop()
        for p in P:
            n = h * p % b
            if n not in H:
                H.add(n)
                frontier.append(n)
    return H


def index(P, b):
    """[Z^k : Lambda_b] = |H_b| (chi_b maps Z^k onto H_b)."""
    return len(subgroup(P, b))


def is_rectangular(P, b):
    """spec 3.2: Lambda_b = (+) o_i Z e_i  <=>  |H_b| = prod o_i."""
    prod = 1
    for o in orders(P, b):
        prod *= o
    return index(P, b) == prod


def chi(alpha, P, b):
    r = 1 % b
    for p, a in zip(P, alpha):
        r = r * pow(p, a, b) % b
    return r


def in_lattice(alpha, P, b):
    return b == 1 or chi(alpha, P, b) == 1


def contains(P, b, b2, window=None):
    """Lambda_b <= Lambda_b2 ?  Exact: Lambda_b is generated by its points in the box [0, prod-of-orders)^... ; we use the fact that
    Lambda_b contains o_i e_i and has index |H_b|, hence is generated by its points in the box [0,o_1]x...x[0,o_k] (every coset of
    (+) o_i Z e_i meets that box).  So inclusion holds iff chi_b2 = 1 on those finitely many points."""
    os_ = orders(P, b)
    return all(in_lattice(a, P, b2) for a in product(*[range(o + 1) for o in os_]) if in_lattice(a, P, b))


def relation(P, b, b2):
    a, c = contains(P, b, b2), contains(P, b2, b)
    return "EQUAL" if a and c else "ENLARGE" if a else "SHRINK" if c else "INCOMPARABLE"


def describe(P, b):
    os_ = orders(P, b)
    prod = 1
    for o in os_:
        prod *= o
    return {"b": b, "primes": list(P), "orders": list(os_), "subgroup_order": index(P, b), "product_of_orders": prod,
            "rectangular": index(P, b) == prod, "nonrectangular": index(P, b) < prod}
