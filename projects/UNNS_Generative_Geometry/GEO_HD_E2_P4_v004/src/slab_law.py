"""P4 slab criterion (v002).  For Lambda' = Lambda'_2 (+) Z e_i (free coordinate i) and 0<c<1:  (x',c) in U(Lambda') <=> x' in U(Lambda'_2).
This module checks, for each recorded 3D failure, that the exact witness lies in the slab 0<w_i<1 over a planar point OUTSIDE U(Lambda'_2),
using an independent planar membership test (Fractions, parallelogram parameters) -- not the 3D engine."""
from fractions import Fraction as Fr
from itertools import product

import _boot  # noqa: F401
import lattice_model as lm


def planar_cells(inL2, q2):
    F, cs = lm.cells_of_member(inL2, q2)
    return F, cs


def _in_cell2(base, gens, p):
    """p in {base + s1 g1 + s2 g2 : 0<=s<=1} for planar (dim<=2) cells, exact."""
    d = [p[0] - base[0], p[1] - base[1]]
    gs = [g for g in gens]
    if not gs:
        return d == [0, 0]
    if len(gs) == 1:
        g = gs[0]
        det = d[0] * g[1] - d[1] * g[0]
        if det != 0:
            return False
        t = Fr(d[0], g[0]) if g[0] else Fr(d[1], g[1])
        return 0 <= t <= 1
    g, h = gs
    det = g[0] * h[1] - g[1] * h[0]
    if det == 0:
        return False
    s = Fr(d[0] * h[1] - d[1] * h[0], det)
    t = Fr(g[0] * d[1] - g[1] * d[0], det)
    return 0 <= s <= 1 and 0 <= t <= 1


def in_union2(cells, p):
    return any(_in_cell2(b, g, p) for b, g in cells)


def slab_record(Bp, q, witness):
    """Bp: HNF basis of the 3D target lattice; q: box; witness: 3 Fraction strings.  Returns the slab diagnostic."""
    inL = lm.member3(Bp)
    w = [Fr(x) for x in witness]
    out = {"free": lm.free_coordinates3(inL), "decomposable": lm.decomposable3(Bp)}
    best = None
    for i in out["free"]:
        rest = [j for j in range(3) if j != i]
        # planar target lattice = Lambda' cap Z^rest  (coordinates re-indexed)
        def inL2(v, i=i, rest=rest):
            full = [0, 0, 0]
            full[rest[0]], full[rest[1]] = v
            return inL(tuple(full))
        F2, cs2 = planar_cells(inL2, tuple(q[j] for j in rest))
        # Lambda' = Lambda'_2 (+) Z e_i  requires Lambda' = (Lambda' cap Z^rest) + Z e_i ; verify on the basis rows
        ok_split = all(inL2((r[rest[0]], r[rest[1]])) for r in Bp)
        slab = 0 < w[i] < 1
        outside = not in_union2(cs2, (w[rest[0]], w[rest[1]]))
        rec = {"i": i, "split": ok_split, "slab": slab, "planar_point": [str(w[rest[0]]), str(w[rest[1]])], "outside_planar_union": outside,
               "planar_box": [q[rest[0]], q[rest[1]]], "planar_target_F": len(F2)}
        rec["slab_witness"] = ok_split and slab and outside
        if best is None or rec["slab_witness"]:
            best = rec
    out["slab"] = best
    return out


def mem_chi(P, b):
    def f(v):
        r = 1
        for p, e in zip(P, v):
            r = r * (pow(p, e, b) if e >= 0 else pow(pow(p, -1, b), -e, b)) % b
        return r % b == 1 % b
    return f


def slab_sample_witness(P, b, b2, q, denom=6):
    """Sufficient test for noncontainment with no 3D target engine: find a point of a source cell with free-coordinate value in (0,1)
    whose planar part is outside U(Lambda'_2).  Returns the witness or None."""
    import exact_containment as ec
    inS, inT = mem_chi(P, b), mem_chi(P, b2)
    F, cs = lm.cells_of_member(inS, tuple(q))
    Smax = ec.geometric_maximal(cs, 3)
    for i in lm.free_coordinates3(inT):
        rest = [j for j in range(3) if j != i]
        def in2(v, i=i, rest=rest):
            full = [0, 0, 0]
            full[rest[0]], full[rest[1]] = v
            return inT(tuple(full))
        F2, cs2 = planar_cells(in2, tuple(q[j] for j in rest))
        for base, gens in Smax:
            for ss in product(range(denom + 1), repeat=len(gens)):
                pt = [Fr(c) + sum(Fr(s, denom) * g[k] for s, g in zip(ss, gens)) for k, c in enumerate(base)]
                if 0 < pt[i] < 1 and not in_union2(cs2, (pt[rest[0]], pt[rest[1]])):
                    return {"i": i, "point": [str(x) for x in pt], "cell": {"base": list(base), "gens": [list(g) for g in gens]}}
    return None


def slab_record_chi(P, b2, q, witness):
    """FIELD-I version: target lattice = ker chi_{b2} on the prime coordinates P."""
    inL = mem_chi(P, b2)
    w = [Fr(x) for x in witness]
    best = None
    for i in lm.free_coordinates3(inL):
        rest = [j for j in range(3) if j != i]

        def in2(v, i=i, rest=rest):
            full = [0, 0, 0]
            full[rest[0]], full[rest[1]] = v
            return inL(tuple(full))
        F2, cs2 = planar_cells(in2, tuple(q[j] for j in rest))
        # planar lattice index (order of the group generated by the two remaining primes mod b2)
        rec = {"i": i, "slab": 0 < w[i] < 1, "outside_planar_union": not in_union2(cs2, (w[rest[0]], w[rest[1]])),
               "planar_point": [str(w[rest[0]]), str(w[rest[1]])], "planar_box": [q[rest[0]], q[rest[1]]], "planar_target_F": len(F2),
               "free_prime": P[i], "planar_primes": [P[rest[0]], P[rest[1]]]}
        rec["slab_witness"] = rec["slab"] and rec["outside_planar_union"]
        best = rec
        if rec["slab_witness"]:
            break
    return {"free": lm.free_coordinates3(inL), "slab": best}
