"""E2-P2 / P2-T1: exact decision of kernel inclusion  ker(chi_b) <= ker(chi_b')  on a common prime set.

chi_b(alpha) = prod p_i^alpha_i mod b  (gcd(p_i,b)=1).  Lambda_b = ker chi_b in Z^k (infinite lattice, not a box).
Three decision procedures are implemented and must agree:
  (K) kernel-generator test : Lambda_b is generated by {m_i e_i} U {alpha in prod[0,m_i): chi_b(alpha)=1}
      (m_i = ord_b(p_i)); inclusion iff every generator lies in Lambda_b'.
  (H) homomorphism test     : the assignment chi_b(alpha) -> chi_b'(alpha) is a well-defined map on H_b = <p_i mod b>
      (including the relations p_i^{m_i}=1), i.e. a homomorphism H_b -> H_b' with p_i mod b |-> p_i mod b'.
  (B) HNF-basis test        : the Hermite basis of Lambda_b lies in Lambda_b'.
Denominator divisibility is NOT used anywhere.
"""
import os
import sys
from functools import lru_cache
from itertools import product
from math import gcd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "inherited"))


def order(p, b):
    if b == 1:
        return 1
    assert gcd(p, b) == 1
    r, n = p % b, 1
    while r != 1:
        r = r * p % b
        n += 1
    return n


def orders(primes, b):
    return tuple(order(p, b) for p in primes)


def chi(alpha, primes, b):
    if b == 1:
        return 0
    r = 1
    for p, a in zip(primes, alpha):
        r = r * pow(pow(p, -1, b) if a < 0 else p, abs(a), b) % b
    return r


def in_lambda(alpha, primes, b):
    return b == 1 or chi(alpha, primes, b) == 1


def _residues(primes, b, ms):
    """[(alpha, chi_b(alpha))] over prod [0,m_i), by incremental power tables (fast)."""
    acc = [((), 1 % b)]
    for p, m in zip(primes, ms):
        t, r = [], 1 % b
        for _ in range(m):
            t.append(r)
            r = r * p % b
        acc = [(al + (i,), c * t[i] % b) for al, c in acc for i in range(m)]
    return acc


@lru_cache(maxsize=None)
def _kernel_generators(primes, b):
    ms = orders(primes, b)
    gens = []
    for i, m in enumerate(ms):
        v = [0] * len(primes)
        v[i] = m
        gens.append(tuple(v))
    one = 1 % b
    for a, c in _residues(primes, b, ms):
        if any(a) and c == one:
            gens.append(a)
    return tuple(gens)


def kernel_generators(primes, b):
    return list(_kernel_generators(tuple(primes), b))


def subgroup_order(primes, b):
    """|H_b| = [Z^k : Lambda_b]."""
    return len({c for _, c in _residues(primes, b, orders(primes, b))})


def included_K(primes, b, b2):
    return all(in_lambda(g, primes, b2) for g in _kernel_generators(tuple(primes), b))


def included_H(primes, b, b2):
    ms = orders(primes, b)
    for i, m in enumerate(ms):
        e = [0] * len(primes)
        e[i] = m
        if not in_lambda(e, primes, b2):
            return False
    f = {}
    for a, s in _residues(primes, b, ms):
        t = chi(a, primes, b2)
        if f.setdefault(s, t) != t:
            return False
    return True


def hnf_basis(vectors, k):
    """Row-style Hermite normal form of the lattice spanned by integer vectors (list of rows)."""
    rows = [list(v) for v in vectors if any(v)]
    basis = []
    for col in range(k):
        while True:
            nz = [r for r in rows if r[col] != 0]
            if len(nz) <= 1:
                break
            nz.sort(key=lambda r: abs(r[col]))
            piv = nz[0]
            for r in nz[1:]:
                q = r[col] // piv[col]
                for j in range(k):
                    r[j] -= q * piv[j]
            rows = [r for r in rows if any(r)]
        nz = [r for r in rows if r[col] != 0]
        if nz:
            piv = nz[0]
            if piv[col] < 0:
                piv[:] = [-t for t in piv]
            basis.append(tuple(piv))
            rows = [r for r in rows if r is not piv]
    return basis


@lru_cache(maxsize=None)
def _hnf(primes, b):
    return tuple(hnf_basis(_kernel_generators(primes, b), len(primes)))


def included_basis(primes, b, b2):
    return all(in_lambda(r, primes, b2) for r in _hnf(tuple(primes), b))


def relation(primes, b, b2):
    """EQUAL / ENLARGE (Lambda_b < Lambda_b2) / SHRINK / INCOMPARABLE, exact on the infinite lattices."""
    primes = tuple(primes)
    a = included_K(primes, b, b2)
    c = included_K(primes, b2, b)
    assert a == included_H(primes, b, b2) == included_basis(primes, b, b2)
    assert c == included_H(primes, b2, b) == included_basis(primes, b2, b)
    if a and c:
        return "EQUAL"
    if a:
        return "ENLARGE"
    if c:
        return "SHRINK"
    return "INCOMPARABLE"


def index_from_basis(basis):
    d = 1
    for i, r in enumerate(basis):
        d *= abs(r[i])
    return d


def describe(primes, b):
    B = list(_hnf(tuple(primes), b))
    return {"b": b, "orders": list(orders(primes, b)), "index": index_from_basis(B), "hnf_basis": [list(r) for r in B]}


def coupled(primes, b):
    """True iff Lambda_b is NOT a direct sum along any nontrivial coordinate partition (genuine coupling)."""
    k = len(primes)
    gens = _kernel_generators(tuple(primes), b)
    for mask in range(1, 2 ** (k - 1)):
        I = [i for i in range(1, k) if (mask >> (i - 1)) & 1]
        if all(in_lambda(tuple(g[i] if i in I else 0 for i in range(k)), primes, b) for g in gens):
            return False
    return True
